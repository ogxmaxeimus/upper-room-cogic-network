function botPhoto(name) {
  return `https://ui-avatars.com/api/?name=${encodeURIComponent(name)}&background=4a3d1f&color=f3e6c4&size=400&bold=true`
}

function makeBot({
  id,
  name,
  jobTitle,
  jobTypeId,
  specialtyId,
  specialty,
  skills,
  location,
  company = 'Upper Room Demo',
}) {
  return {
    id,
    name,
    profilePhoto: botPhoto(name),
    jobTitle,
    jobTypeId,
    specialtyId,
    specialty,
    skills,
    yearsExperience: 6,
    company,
    location,
    bio: `Demo profile in ${location}. Used to prove the network globe points to this state, then lists its cities and the members in that area. Not a real congregation member.`,
    portfolio: null,
    availability: ['Freelance'],
    socialLinks: {},
    rating: null,
    endorsements: 0,
    endorsementQuotes: [],
    verified: false,
    featured: false,
    isBot: true,
    actionsDisabled: true,
    joinedAt: '2024-01-15',
    listOrder: 10,
    affiliation: 'Demo profile',
  }
}

